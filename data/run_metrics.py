"""
Build the schema in DuckDB, load the seed CSVs, run every named query in sql/metrics/
and write the results to data/metric_snapshot.md.

This is the test harness for the SQL: if a query is wrong, it fails here.
The SQL itself is Postgres-dialect so it runs unchanged on Supabase.

Run:  python data/run_metrics.py [--start 2026-09-01 --end 2026-09-30]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = sorted((ROOT / "sql" / "schema").glob("*.sql"))
METRICS = sorted((ROOT / "sql" / "metrics").glob("*.sql"))
SEED = ROOT / "data" / "seed"

# FK-safe load order
LOAD_ORDER = [
    "monthly_targets", "campaigns", "landing_pages", "ad_sets", "ads", "ad_daily_metrics",
    "ad_set_weekly_frequency", "landing_page_daily", "leads", "lead_stage_events", "workshops",
    "enrollments", "invoices", "payments", "workshop_seats",
    "advisors", "students", "subjects", "chapters", "chapter_stage_events", "exam_targets", "exam_results",
    "tasks", "timetable_blocks", "focus_sessions", "quizzes", "quiz_attempts", "wearable_daily",
    "app_daily_usage", "activities", "activity_participants", "soft_skill_scores", "roadmap_milestones",
    "escalations", "event_feature_map", "app_events",
]

# The app-adoption queries use the brief's own Mixpanel window.
WINDOWS = {"50_app_adoption.sql": ("2026-08-30", "2026-10-13")}


def split_named(sql: str) -> list[tuple[str, str]]:
    parts = re.split(r"^-- name: (\w+)\s*$", sql, flags=re.M)
    return [(parts[i], parts[i + 1].strip()) for i in range(1, len(parts), 2)]


def to_md(cols, rows, limit=25) -> str:
    def cell(v):
        if v is None:
            return ""
        if isinstance(v, float):
            return f"{v:,.2f}"
        return str(v).replace("|", "/")
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows[:limit]]
    if len(rows) > limit:
        out.append(f"\n_{len(rows) - limit} more rows not shown_")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--start", default="2026-09-01")
    ap.add_argument("--end", default="2026-09-30")
    ap.add_argument("--as-of", default="2026-10-15")
    args = ap.parse_args()

    con = duckdb.connect()
    for f in SCHEMA:
        con.execute(f.read_text(encoding="utf-8"))
    for t in LOAD_ORDER:
        src = (f"read_csv('{(SEED / (t + '.csv')).as_posix()}', header=true, nullstr='', "
               f"auto_type_candidates=['BOOLEAN','BIGINT','DOUBLE','DATE','TIMESTAMP','VARCHAR'])")
        if t == "enrollments":
            # self-referencing FK: DuckDB checks per row, so parents (trials) go in first
            con.execute(f"INSERT INTO {t} SELECT * FROM {src} WHERE renewed_from IS NULL")
            con.execute(f"INSERT INTO {t} SELECT * FROM {src} WHERE renewed_from IS NOT NULL")
        else:
            con.execute(f"INSERT INTO {t} SELECT * FROM {src}")

    report = [f"# Metric snapshot\n\nGenerated by `data/run_metrics.py` against the dummy seed. "
              f"GTM and student window: **{args.start} to {args.end}**, as of **{args.as_of}**.\n"]
    failures = 0
    for f in METRICS:
        start, end = WINDOWS.get(f.name, (args.start, args.end))
        report.append(f"\n## {f.name}\n")
        for name, q in split_named(f.read_text(encoding="utf-8")):
            q = q.replace("{{start_date}}", start).replace("{{end_date}}", end).replace("{{as_of}}", args.as_of)
            try:
                cur = con.execute(q)
                cols = [d[0] for d in cur.description]
                rows = cur.fetchall()
                report.append(f"### {name}\n\n{to_md(cols, rows)}\n")
                print(f"  ok    {f.name:<30} {name:<30} {len(rows):>4} rows")
            except Exception as e:  # noqa: BLE001 - report every broken query, not just the first
                failures += 1
                report.append(f"### {name}\n\n**FAILED:** `{e}`\n")
                print(f"  FAIL  {f.name:<30} {name:<30} {e}")
    (ROOT / "data" / "metric_snapshot.md").write_text("\n".join(report), encoding="utf-8")
    print(f"\n{'All queries ran.' if not failures else f'{failures} queries failed.'} -> data/metric_snapshot.md")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
